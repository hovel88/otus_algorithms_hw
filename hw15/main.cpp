#include <string>
#include "graph.h"

// --- ГРАФЫ ДЛЯ ТЕСТИРОВАНИЯ
//     генерируем граф в виде ступенчатых массивов смежности (для простоты)

enum graph_type {
    GT_0,
    GT_1,   // обычный DAG
            // 0 -> 1, 0 -> 2
            // 1 -> 2, 1 -> 3
            // 2 -> 3
    GT_2,   // DAG с несколькими вершинами на одном уровне
            // 0 -> 2, 0 -> 3
            // 1 -> 3, 1 -> 4
            // 2 -> 5
            // 3 -> 5
            // 4 -> 5
    GT_3,   // более сложный DAG
            // 0 -> 3, 0 -> 4
            // 1 -> 4, 1 -> 5
            // 2 -> 5
            // 3 -> 6, 3 -> 7
            // 4 -> 6, 4 -> 8
            // 5 -> 7, 5 -> 8
            // 6 -> 9
            // 7 -> 9
            // 8 -> 9
            // 9 -> (нет исходящих)
    GT_4    // граф с циклом (должен выдать ошибку из-за цикла)
            // 0 -> 1 -> 2 -> 0
};

std::vector<std::vector<int>> create_graph(graph_type gt) {
    switch (gt) {
    case GT_0:  return {
                    {1, 3},     // 0 -> 1, 0 -> 3
                    {5},        // 1 -> 5
                    {1},        // 2 -> 1
                    {5},        // 3 -> 5
                    {},         // 4 -> (нет исходящих)
                    {4}         // 5 -> 4
                };
    case GT_1:  return {
                    {1, 2},     // 0 -> 1, 0 -> 2
                    {2, 3},     // 1 -> 2, 1 -> 3
                    {3},        // 2 -> 3
                    {}          // 3 -> (нет исходящих)
                };
    case GT_2:  return {
                    {2, 3},     // 0 -> 2, 0 -> 3
                    {3, 4},     // 1 -> 3, 1 -> 4
                    {5},        // 2 -> 5
                    {5},        // 3 -> 5
                    {5},        // 4 -> 5
                    {}          // 5 -> (нет исходящих)
                };
    case GT_3:  return {
                    {3, 4},     // 0 -> 3, 0 -> 4
                    {4, 5},     // 1 -> 4, 1 -> 5
                    {5},        // 2 -> 5
                    {6, 7},     // 3 -> 6, 3 -> 7
                    {6, 8},     // 4 -> 6, 4 -> 8
                    {7, 8},     // 5 -> 7, 5 -> 8
                    {9},        // 6 -> 9
                    {9},        // 7 -> 9
                    {9},        // 8 -> 9
                    {}          // 9 -> (нет исходящих)
                };
    case GT_4:  return {
                    {1},        // 0 -> 1
                    {2},        // 1 -> 2
                    {0},        // 2 -> 0
                    {}          // 3 изолирована
                };
    default:    return {};
    }
}

int main(int argc, char** argv)
{
    std::cout << "Программа для демонстрации топологической сортировки графов\n";

    struct graphs {
        std::string                   name{};
        std::vector<std::vector<int>> graph{};
    };
    std::vector<graphs> collection = {{
        {"DAG0",                            create_graph(GT_0)},
        {"DAG1 (линейный с ветвлениями)",   create_graph(GT_1)},
        {"DAG2 (широкий граф, 2 уровня)",   create_graph(GT_2)},
        {"DAG3 (многоуровневый граф)",      create_graph(GT_3)},
        {"граф с циклом (не DAG)",          create_graph(GT_4)}
    }};

    for (size_t idx = 0; idx < collection.size(); ++idx) {
        std::cout << "\n" << "тест: " << collection[idx].name << "\n\n";

        Graph graph(collection[idx].graph);
        graph.print();
        auto [success, levels] = graph.demucron_sort();
        if (success) {
            std::cout << "\nУСПЕХ: топологическая сортировка алгоритмом Демукрона выполнена\n";
            levels.print();
        } else {
            std::cout << "\nОШИБКА: граф содержит цикл! топологическая сортировка невозможна\n";
        }

        std::cout << "\n" << std::string(70, '-') << "\n";
    }

    return 0;
}
